let productsPromise = null;

/** Hydrate the compact index into plain product objects. */
export function loadProducts() {
  if (!productsPromise) {
    productsPromise = getJSON('index').then((idx) => {
      const fields = idx.fields;
      return idx.rows.map((row) => {
        const p = {};
        fields.forEach((f, i) => { p[f] = row[i]; });
        p.href = `/Crazy-Vinyl-Shop/proizvod/${p.slug}/`;
p.image = `/Crazy-Vinyl-Shop/assets/images/products/${p.slug}.jpg`;
        return p;
      });
    });
  }
  return productsPromise;
}

export const loadSite = () => getJSON('site');
export const loadCategories = () => getJSON('categories');

let imagesPromise = null;

/** Set of slugs with a real artwork file, so we never request a missing one. */
export function loadImageManifest() {
  if (!imagesPromise) {
    imagesPromise = getJSON('images')
      .then((list) => new Set(list))
      .catch(() => new Set());
  }
  return imagesPromise;
}

