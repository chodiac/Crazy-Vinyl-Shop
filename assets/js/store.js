const nf = new Intl.NumberFormat('sr-RS', { maximumFractionDigits: 0 });

export function formatPrice(value) {
  if (value === null || value === undefined || value === '') return 'Cena na upit';
  return `${nf.format(value)} RSD`;
}

export const formatNumber = (n) => nf.format(n);

/** Display name: "ARTIST — Title", falling back to whichever exists. */
export function displayName(p) {
  return [p.artist, p.title].filter(Boolean).join(' – ') || p.slug;
}

/** Metadata line for a card: FORMAT · GENRE · YEAR, empties dropped. */
export function taxonomyLine(p) {
  return [p.format, p.genre, p.year].filter(Boolean).join(' · ');
}

/* --------------------------------------------------------------------------
   sale handling — a product is on sale only when the source data says so
   -------------------------------------------------------------------------- */

export const isOnSale = (p) => Boolean(p.onSale) && p.salePrice > 0 && p.salePrice < p.price;
export const effectivePrice = (p) => (isOnSale(p) ? p.salePrice : p.price);

/* --------------------------------------------------------------------------
   queries
   -------------------------------------------------------------------------- */

export const byCategory = (products, slug) => products.filter((p) => p.category === slug);
export const onSaleOnly = (products) => products.filter((p) => isOnSale(p));

/** Newest first, using the real publish date from the source site. */
export function newest(products, limit) {
  const sorted = [...products].sort(
    (a, b) => (b.addedAt || '').localeCompare(a.addedAt || '') || Number(b.id) - Number(a.id),
  );
  return typeof limit === 'number' ? sorted.slice(0, limit) : sorted;
}

export function findBySlug(products, slug) {
  return products.find((p) => p.slug === slug) || null;
}

/** Same genre first, then same format; used for "more from the crate". */
export function related(products, product, limit = 8) {
  const pool = products.filter((p) => p.slug !== product.slug);
  const score = (p) => (p.genre && p.genre === product.genre ? 2 : 0)
    + (p.format && p.format === product.format ? 1 : 0)
    + (p.available ? 0.5 : 0);
  return pool
    .map((p) => [score(p), p])
    .filter(([s]) => s > 0)
    .sort((a, b) => b[0] - a[0] || (b[1].addedAt || '').localeCompare(a[1].addedAt || ''))
    .slice(0, limit)
    .map(([, p]) => p);
}

/* --------------------------------------------------------------------------
   search — artist, title, genre, format
   -------------------------------------------------------------------------- */

/** Fold Serbian diacritics so "soljе"/"šolje" and "zanr"/"žanr" both match. */
export function fold(s) {
  return (s || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/đ/g, 'dj')
    .replace(/ð/g, 'dj');
}

export function searchProducts(products, query, limit = 40) {
  const q = fold(query).trim();
  if (q.length < 2) return [];
  const terms = q.split(/\s+/);
  const scored = [];

  for (const p of products) {
    const artist = fold(p.artist);
    const title = fold(p.title);
    const hay = `${artist} ${title} ${fold(p.genre)} ${fold(p.format)}`;
    if (!terms.every((t) => hay.includes(t))) continue;

    let score = 0;
    if (artist.startsWith(q)) score += 100;
    else if (artist.includes(q)) score += 60;
    if (title.startsWith(q)) score += 50;
    else if (title.includes(q)) score += 30;
    if (p.available) score += 8;
    scored.push([score, p]);
  }

  return scored
    .sort((a, b) => b[0] - a[0] || (b[1].addedAt || '').localeCompare(a[1].addedAt || ''))
    .slice(0, limit)
    .map(([, p]) => p);
}

/* --------------------------------------------------------------------------
   facets — every filter value is derived from the data, never hardcoded
   -------------------------------------------------------------------------- */

export const FACET_KEYS = ['category', 'genre', 'format', 'year', 'country', 'condition', 'origin', 'availability'];

const AVAILABILITY = {
  available: (p) => p.available,
  sold: (p) => !p.available,
  sale: (p) => isOnSale(p),
};

/** Count each facet value across a product set. */
export function buildFacets(products) {
  const facets = {};
  for (const key of FACET_KEYS) facets[key] = new Map();

  for (const p of products) {
    for (const key of ['category', 'genre', 'format', 'country', 'condition', 'origin']) {
      const v = p[key];
      if (!v) continue;
      facets[key].set(v, (facets[key].get(v) || 0) + 1);
    }
    if (p.year) facets.year.set(String(p.year), (facets.year.get(String(p.year)) || 0) + 1);
    for (const [k, test] of Object.entries(AVAILABILITY)) {
      if (test(p)) facets.availability.set(k, (facets.availability.get(k) || 0) + 1);
    }
  }
  return facets;
}

export function priceBounds(products) {
  const prices = products.map(effectivePrice).filter((n) => typeof n === 'number' && n > 0);
  if (!prices.length) return { min: 0, max: 0 };
  return { min: Math.min(...prices), max: Math.max(...prices) };
}

/* --------------------------------------------------------------------------
   filtering + sorting
   -------------------------------------------------------------------------- */

/**
 * All active groups apply together (AND across groups, OR inside a group).
 * `state` shape: { category:Set, genre:Set, ..., q:string, min:number, max:number }
 */
export function applyFilters(products, state) {
  const q = fold(state.q || '').trim();
  const terms = q.length >= 2 ? q.split(/\s+/) : null;

  return products.filter((p) => {
    for (const key of ['category', 'genre', 'format', 'country', 'condition', 'origin']) {
      const set = state[key];
      if (set && set.size && !set.has(p[key])) return false;
    }
    if (state.year && state.year.size && !state.year.has(String(p.year))) return false;

    if (state.availability && state.availability.size) {
      let ok = false;
      for (const v of state.availability) {
        if (AVAILABILITY[v] && AVAILABILITY[v](p)) { ok = true; break; }
      }
      if (!ok) return false;
    }

    const price = effectivePrice(p);
    if (state.min && !(price >= state.min)) return false;
    if (state.max && !(price <= state.max)) return false;

    if (terms) {
      const hay = `${fold(p.artist)} ${fold(p.title)} ${fold(p.genre)} ${fold(p.format)}`;
      if (!terms.every((t) => hay.includes(t))) return false;
    }
    return true;
  });
}

