/* ==========================================================================
   store.js — the single data source for the storefront.

   Everything (home, catalogue, search, filters, cart, checkout) reads from
   here. Product metadata is never duplicated in a component.

   data/products.json  canonical, human-readable catalogue (edit this)
   data/index.json     compact listing index, generated by tools/build.py
   data/images.json    slugs that have a real image file on disk
   ========================================================================== */

const BASE = new URL('../../data', import.meta.url).pathname.replace(/\/$/, '');

/** Categories that exist as routes even when empty. */
export const CATEGORY_ORDER = ['ploce', 'diskovi', 'majice', 'solje', 'ostalo'];

const cache = new Map();

async function getJSON(name) {
  if (!cache.has(name)) {
    cache.set(name, fetch(`${BASE}/${name}.json`, { cache: 'no-cache' }).then((r) => {
      if (!r.ok) throw new Error(`${name}.json → ${r.status}`);
      return r.json();
    }));
  }
  return cache.get(name);
}

