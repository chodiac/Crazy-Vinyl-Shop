const collator = new Intl.Collator('sr-RS', { sensitivity: 'base', numeric: true });

export function sortProducts(products, sort) {
  const out = [...products];
  const price = (p) => effectivePrice(p) ?? Number.POSITIVE_INFINITY;

  switch (sort) {
    case 'price-asc': out.sort((a, b) => price(a) - price(b)); break;
    case 'price-desc': out.sort((a, b) => price(b) - price(a)); break;
    case 'artist-asc':
      out.sort((a, b) => collator.compare(a.artist || a.title || '', b.artist || b.title || ''));
      break;
    case 'year-desc': out.sort((a, b) => (b.year || 0) - (a.year || 0)); break;
    case 'year-asc':
      out.sort((a, b) => (a.year || Number.POSITIVE_INFINITY) - (b.year || Number.POSITIVE_INFINITY));
      break;
    default:
      out.sort((a, b) => (b.addedAt || '').localeCompare(a.addedAt || '') || Number(b.id) - Number(a.id));
  }
  return out;
}

