def asset_fingerprint():
    """Short hash of every stylesheet and script, for cache-busting."""
    h = hashlib.sha1()
    for folder in ('css', 'js'):
        d = os.path.join(ROOT, 'assets', folder)
        for name in sorted(os.listdir(d)):
            if name.endswith(('.css', '.js')):
                with open(os.path.join(d, name), 'rb') as fh:
                    h.update(name.encode())
                    h.update(fh.read())
    return h.hexdigest()[:8]


def read(name):
    with open(os.path.join(DATA, name), encoding='utf-8') as fh:
        return json.load(fh)


LINK_RE = re.compile(r'((?:href|src)=")/([^"]*)"')


def path_prefix(rel_out, base):
    """How this page should reach the site root.

    Pages are generated with root-absolute links (/assets/..., /proizvod/...)
    and rewritten here. Without --base that becomes a relative hop, so the site
    works at a domain root, inside a GitHub Pages project sub-path, or straight
    off the file system. With --base it becomes an absolute path under that
    prefix, which is what a project site needs for 404.html to resolve from any
    depth.
    """
    if base:
        return base.rstrip('/') + '/'
    depth = rel_out.replace(os.sep, '/').count('/')
    return './' if depth == 0 else '../' * depth


def localize(html, rel_out, base):
    prefix = path_prefix(rel_out, base)
    return LINK_RE.sub(lambda m: m.group(1) + prefix + m.group(2) + '"', html)


def write(rel, content):
    path = os.path.join(ROOT, rel.replace('/', os.sep))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(content)


def price_txt(value):
    if value is None or value == '':
        return 'Cena na upit'
    return f'{value:,}'.replace(',', '.') + ' RSD'


def eff_price(p):
    if p.get('onSale') and p.get('salePrice'):
        return p['salePrice']
    return p.get('price')


def tax_line(p):
    return ' · '.join(str(x) for x in (p.get('format'), p.get('genre'), p.get('year')) if x)


def display_name(p):
    return ' – '.join(x for x in (p.get('artist'), p.get('title')) if x) or p['slug']


