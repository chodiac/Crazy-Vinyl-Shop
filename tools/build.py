def find_logo(stem, fallback=None):
    """The shop's own file for this slot, whatever format it arrived in.

    `fallback` lets one master serve several slots — the shop has a single
    transparent logo it wants everywhere, so the record label falls back to it
    rather than needing its own copy.
    """
    for name in (stem, fallback):
        if not name:
            continue
        for ext in ('svg', 'png', 'webp', 'jpg', 'jpeg'):
            path = os.path.join(ROOT, 'images', name + '.' + ext)
            if os.path.isfile(path):
                return path
    return None


def prepare_logo(stem, target_px, fallback=None):
    """Return the URL to use for a logo slot, resizing the master if needed.

    The file dropped into images/ is usually an export at full resolution — the
    header mark renders at well under 60px, so serving a 1254px master there
    would cost more than every other asset on the page put together. A
    derivative is generated beside it and referenced instead; the master stays
    untouched as the source, and is re-derived whenever it changes.
    """
    src = find_logo(stem, fallback)
    if not src:
        return None, None

    name = os.path.basename(src)
    if src.lower().endswith('.svg'):
        return '/images/' + name, None  # already resolution-independent

    try:
        from PIL import Image
    except ImportError:
        # No Pillow: ship the master rather than no logo, and say so.
        return '/images/' + name, 'master (install Pillow to resize)'

    out_dir = os.path.join(ROOT, 'images', 'gen')
    os.makedirs(out_dir, exist_ok=True)
    out_name = '%s-%d.webp' % (os.path.splitext(os.path.basename(src))[0], target_px)
    out_path = os.path.join(out_dir, out_name)

    if not os.path.isfile(out_path) or os.path.getmtime(out_path) < os.path.getmtime(src):
        im = Image.open(src)
        im = im.convert('RGBA') if im.mode in ('RGBA', 'LA', 'P') else im.convert('RGB')
        if im.width > target_px:
            height = max(1, round(im.height * target_px / im.width))
            im = im.resize((target_px, height), Image.LANCZOS)
        im.save(out_path, 'WEBP', quality=88, method=6)

    saved = '%dkB from %dkB' % (
        round(os.path.getsize(out_path) / 1024), round(os.path.getsize(src) / 1024))
    return '/images/gen/' + out_name, saved


