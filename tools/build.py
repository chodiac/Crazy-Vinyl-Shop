POS_RE = re.compile(r'^([A-Fa-f])(\d{1,2})?\s*[–\-\.]?\s*(.*)$')
DUR_RE = re.compile(r'\s(\d{1,2}:\d{2})\s*$')


def split_tracks(tracks):
    """Group into sides when the source positions make that possible.

    Returns [(side_label, [(position, name, duration), ...]), ...].
    Track names are preserved exactly as the source shows them.
    """
    sides = []
    current = None
    plain = []

    for raw in tracks:
        m = POS_RE.match(raw)
        side = m.group(1).upper() if m and m.group(2) else None
        if side:
            pos = f'{side}{m.group(2)}'
            name = m.group(3).strip()
            if not name:
                name = raw
            if current is None or current[0] != side:
                current = (side, [])
                sides.append(current)
            d = DUR_RE.search(name)
            dur = d.group(1) if d else ''
            if dur:
                name = DUR_RE.sub('', name).strip()
            current[1].append((pos, name, dur))
        else:
            plain.append(raw)

    if sides and not plain:
        return sides
    if sides and plain:
        # keep the stray lines (announcements, venue notes) in their own block
        return sides + [('', [('', t, '') for t in plain])]
    return [('', [('', t, '') for t in plain])] if plain else []


def tracks_markup(tracks):
    groups = split_tracks(tracks)
    if not groups:
        return ''
    only = len(groups) == 1
    out = []
    for side, rows in groups:
        if side:
            label = f'Strana {side}'
        elif only:
            label = 'Numere'
        else:
            # lines the source carries alongside the sides (venue, broadcast notes)
            label = 'Uz izdanje'
        head = f'<p class="tracks__sidehead">{label}</p>'
        body = ''.join(
            f'''<div class="tracks__row">
              <span class="tracks__pos">{e(pos) if pos else '·'}</span>
              <span class="tracks__name">{e(name)}{f'<span class="dur">{e(dur)}</span>' if dur else ''}</span>
            </div>''' for pos, name, dur in rows
        )
        out.append(f'<div class="tracks__side">{head}{body}</div>')
    return f'<div class="tracks">{"".join(out)}</div>'


