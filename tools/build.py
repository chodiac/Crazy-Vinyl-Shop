def find_logo(stem, fallback=None):
    """The shop's own file for this slot, whatever format it arrived in.

    `fallback` lets one master serve several slots — the shop has a single
    transparent logo it wants everywhere, so the record label falls back to it
    rather than needing its own copy.
    """
    for name in (stem, fallback):
        if not name:
            continue
        for ext in ('svg', 'png', 'webp', 'jpg', 'jpeg'):
            path = os.path.join(ROOT, 'images', name + '.' + ext)
            if os.path.isfile(path):
                return path
    return None


def prepare_logo(stem, target_px, fallback=None):
    """Return the URL to use for a logo slot, resizing the master if needed.

    The file dropped into images/ is usually an export at full resolution — the
    header mark renders at well under 60px, so serving a 1254px master there
    would cost more than every other asset on the page put together. A
    derivative is generated beside it and referenced instead; the master stays
    untouched as the source, and is re-derived whenever it changes.
    """
    src = find_logo(stem, fallback)
    if not src:
        return None, None

    name = os.path.basename(src)
    if src.lower().endswith('.svg'):
        return '/images/' + name, None  # already resolution-independent

    try:
        from PIL import Image
    except ImportError:
        # No Pillow: ship the master rather than no logo, and say so.
        return '/images/' + name, 'master (install Pillow to resize)'

    out_dir = os.path.join(ROOT, 'images', 'gen')
    os.makedirs(out_dir, exist_ok=True)
    out_name = '%s-%d.webp' % (os.path.splitext(os.path.basename(src))[0], target_px)
    out_path = os.path.join(out_dir, out_name)

    if not os.path.isfile(out_path) or os.path.getmtime(out_path) < os.path.getmtime(src):
        im = Image.open(src)
        im = im.convert('RGBA') if im.mode in ('RGBA', 'LA', 'P') else im.convert('RGB')
        if im.width > target_px:
            height = max(1, round(im.height * target_px / im.width))
            im = im.resize((target_px, height), Image.LANCZOS)
        im.save(out_path, 'WEBP', quality=88, method=6)

    saved = '%dkB from %dkB' % (
        round(os.path.getsize(out_path) / 1024), round(os.path.getsize(src) / 1024))
    return '/images/gen/' + out_name, saved


def main():
    ap = argparse.ArgumentParser(description='Build the Crazy Vinyl Shop site.')
    ap.add_argument('--base', default='',
                    help='Sub-path the site is served from, e.g. /crazy-vinyl-shop '
                         'for a GitHub Pages project site. Omit for relative links.')
    args = ap.parse_args()
    base = args.base.strip()
    if base and not base.startswith('/'):
        base = '/' + base

    # header mark renders under 80px; the record label up to ~340px; the hero
    # lockup as wide as the hero column
    set_asset_version(asset_fingerprint())
    set_js_modules(js_modules())

    logo, logo_note = prepare_logo('logo', 256)
    label_logo, label_note = prepare_logo('logo-label', 640, fallback='logo')
    wordmark, wordmark_note = prepare_logo('natpislogo2', 1000, fallback='natpislogo')
    set_logos(logo, label_logo, wordmark)

    products = read('products.json')
    site = read('site.json')
    categories = read('categories.json')
    privacy = read('privacy.json')
    pages = read('pages.json')

    # A product hidden in the CMS leaves the site completely: no page, no row
    # in the listing index, no sitemap entry. Half-hiding it would leave a
    # reachable page that search engines keep serving.
    hidden = [p for p in products if p.get('hidden')]
    products = [p for p in products if not p.get('hidden')]

    counts = Counter(p['category'] for p in products)
    genre_counts = Counter(p['genre'] for p in products if p.get('genre'))
    top_genres = [g for g, _ in genre_counts.most_common(6)]

    # ---- compact listing index -------------------------------------------
    rows = []
    for p in products:
        rows.append([
            p['id'], p['slug'], p.get('artist', ''), p.get('title', ''), p['category'],
            p.get('price'), p.get('salePrice') or 0, p.get('currency', 'RSD'),
            bool(p['available']), bool(p.get('onSale')), p.get('condition', ''),
            p.get('format', ''), p.get('genre', ''), p.get('year'), p.get('country', ''),
            p.get('origin', ''), p.get('addedAt', ''),
            len(p.get('tracklist') or []), bool(p.get('notes')),
            bool(p.get('featured')),
        ])
    write('data/index.json', json.dumps({'fields': INDEX_FIELDS, 'rows': rows}, ensure_ascii=False))

    # ---- image manifest ---------------------------------------------------
    # {slug: {url, alt}}. Two sources, merged: whatever `content.py pull` wrote
    # from the CMS, plus any file sitting in images/products/. A file in the
    # repo wins, so a hand-placed sleeve is never overridden by the database.
    manifest = {}
    try:
        existing = read('images.json')
        if isinstance(existing, dict):
            manifest.update(existing)
    except (FileNotFoundError, ValueError):
        pass

    img_dir = os.path.join(ROOT, 'images', 'products')
    os.makedirs(img_dir, exist_ok=True)
    for f in sorted(os.listdir(img_dir)):
        stem, ext = os.path.splitext(f)
        if ext.lower() in ('.jpg', '.jpeg', '.png', '.webp', '.avif'):
            manifest[stem] = {'url': f'/images/products/{f}',
                              'alt': manifest.get(stem, {}).get('alt', '')}

    write('data/images.json', json.dumps(manifest, ensure_ascii=False))
    have = sorted(manifest)

    shell = dict(site=site, categories=categories, counts=counts, genres=top_genres)
    written = []

    def emit(rel, **kw):
        write(rel, localize(page(**kw, **shell), rel, base))
        written.append(rel)

    # ---- home ------------------------------------------------------------
    emit('index.html',
         title=pages['home']['seoTitle'],
         description=pages['home']['seoDescription'] or site['brand']['description'],
         path='/', page_kind='home',
         body=home_body(site, categories, counts, products, pages, wordmark),
         jsonld={
             '@context': 'https://schema.org', '@type': 'Store',
             'name': 'Crazy Vinyl Shop', 'url': SITE_URL,
             'telephone': site['store']['phone'], 'email': site['store']['email'],
             'address': {'@type': 'PostalAddress', 'streetAddress': site['store']['street'],
                         'addressLocality': site['store']['city'], 'addressCountry': 'RS'},
             'sameAs': [s['url'] for s in site['social']],
         })

    # ---- catalogue -------------------------------------------------------
    cat = pages['catalog']
    emit('proizvodi/index.html',
         title=cat['seoTitle'],
         description=f"{cat['seoDescriptionPrefix']} {len(products)} {cat['seoDescriptionSuffix']}",
         path='/proizvodi/', page_kind='shop',
         body=shop_body(title=e(cat['title']),
                        lede=f"{e(cat['ledePrefix'])} {len(products)} {e(cat['ledeSuffix'])}",
                        title_key='catalog.title',
                        categories=categories, current='all',
                        breadcrumb=[('Početna', '/'), ('Proizvodi', None)]))

    for c in categories:
        n = counts.get(c['slug'], 0)
        empty_hint = ''
        if n == 0:
            empty_hint = f'''<div class="empty" style="margin-top:2rem">
              <div class="empty__disc">{vinyl(label=c['code'], spin=False)}</div>
              <p class="t-display">{e(c['emptyState'])}</p>
              <p class="text-dim" style="max-width:44ch">{e(pages['category']['emptyHintBody'])}</p>
              <a class="btn" href="{e(pages['category']['emptyHintCtaHref'])}">{e(pages['category']['emptyHintCtaLabel'])}</a>
            </div>'''
        emit(f'{c["slug"]}/index.html',
             title=f'{c["label"]} | Crazy Vinyl Shop',
             description=f'{c["blurb"]} {n} naslova u ponudi.' if n else f'{c["blurb"]} {c["emptyState"]}',
             path=c['href'], page_kind='shop',
             body=shop_body(title=e(c['label']), lede=e(c['blurb']),
                            title_key=f"categories.{c['slug']}.label",
                            lede_key=f"categories.{c['slug']}.blurb",
                            categories=categories, current=c['slug'],
                            breadcrumb=[('Početna', '/'), ('Proizvodi', '/proizvodi/'), (c['label'], None)],
                            empty_hint=empty_hint))

    # ---- sale ------------------------------------------------------------
    on_sale = [p for p in products if p.get('onSale') and p.get('salePrice')]
    sl = pages['sale']
    sale_empty = '' if on_sale else f'''<div class="empty" style="margin-top:2rem">
      <div class="empty__disc">{vinyl(label='SALE', spin=False)}</div>
      <p class="t-display" data-cms="sale.emptyTitle">{e(sl['emptyTitle'])}</p>
      <p class="text-dim" style="max-width:46ch" data-cms="sale.emptyBody">{e(sl['emptyBody'])}</p>
      <div style="display:flex;gap:.6rem;flex-wrap:wrap;justify-content:center">
        <a class="btn btn--sale" href="{e(sl['emptyPrimaryHref'])}" data-cms="sale.emptyPrimaryLabel">{e(sl['emptyPrimaryLabel'])}</a>
        <a class="btn btn--ghost" href="{e(sl['emptySecondaryHref'])}" data-cms="sale.emptySecondaryLabel">{e(sl['emptySecondaryLabel'])}</a>
      </div>
    </div>'''

    sale_head = f'''<section class="page-head sale-head">
  <div class="wrap page-head__inner">
    {crumbs([('Početna', '/'), ('Rasprodaja', None)])}
    <h1 class="sale-head__title"><span data-cms="sale.titleLine1">{e(sl['titleLine1'])}</span><br><span data-cms="sale.titleLine2">{e(sl['titleLine2'])}</span></h1>
    <p class="page-head__lede" data-cms="sale.lede">{e(sl['lede'])}</p>
  </div>
</section>
<div class="sale-strip">{marquee(sl['marquee'], speed='28s')}</div>'''

    emit('rasprodaja/index.html',
         title=sl['seoTitle'],
         description=sl['seoDescription'],
         path='/rasprodaja/', page_kind='shop', body_class='is-sale',
         body=sale_head + shop_main(categories=categories, current='rasprodaja',
                                    empty_hint=sale_empty))

    # ---- product pages ---------------------------------------------------
    by_slug = {}
    for p in products:
        by_slug.setdefault(p['slug'], p)

    for p in by_slug.values():
        label = display_name(p)
        desc_bits = [x for x in (p.get('format'), p.get('genre'), p.get('year'), p.get('country')) if x]
        desc = f'{label} — {", ".join(str(x) for x in desc_bits)}. {price_txt(eff_price(p))}.'
        if not p['available']:
            desc += ' Rasprodato.'
        offer = {
            '@type': 'Offer',
            'priceCurrency': 'RSD',
            'availability': 'https://schema.org/InStock' if p['available'] else 'https://schema.org/OutOfStock',
            'url': f"{SITE_URL}/proizvod/{p['slug']}/",
        }
        if eff_price(p):
            offer['price'] = eff_price(p)
        emit(f'proizvod/{p["slug"]}/index.html',
             title=p.get('seoTitle') or f'{label} | Crazy Vinyl Shop',
             description=p.get('seoDescription') or desc[:300],
             path=f'/proizvod/{p["slug"]}/', page_kind='product', og_type='product',
             body=product_body(p, site, by_slug),
             jsonld={
                 '@context': 'https://schema.org', '@type': 'Product',
                 'name': label,
                 'sku': p.get('catalogNumber') or f"CVS-{p['id']}",
                 'brand': {'@type': 'Brand', 'name': p.get('artist') or 'Crazy Vinyl Shop'},
                 'category': p['category'],
                 'offers': offer,
             })

    # ---- the rest --------------------------------------------------------
    emit('korpa/index.html', title=pages['cart']['seoTitle'],
         description=pages['cart']['seoDescription'], path='/korpa/',
         page_kind='cart', body=cart_body(pages))

    emit('checkout/index.html', title=pages['checkout']['seoTitle'],
         description=pages['checkout']['seoDescription'],
         path='/checkout/', page_kind='checkout', body=checkout_body(site, pages))

    emit('kontakt/index.html', title=pages['contact']['seoTitle'],
         description=pages['contact']['seoDescription'] or
         f'Crazy Vinyl Shop, {site["store"]["address"]}. Telefon {site["store"]["phone"]}. Sicario Tattoo Studio.',
         path='/kontakt/', page_kind='contact', body=contact_body(site, pages),
         jsonld={
             '@context': 'https://schema.org', '@type': 'Store',
             'name': 'Crazy Vinyl Shop',
             'address': {'@type': 'PostalAddress', 'streetAddress': site['store']['street'],
                         'addressLocality': site['store']['city'], 'addressCountry': 'RS'},
             'telephone': site['store']['phone'], 'email': site['store']['email'],
         })

    emit('politika-privatnosti/index.html', title=pages['privacy']['seoTitle'],
         description=pages['privacy']['seoDescription'],
         path='/politika-privatnosti/', page_kind='doc', body=privacy_body(privacy, pages))

    emit('404.html', title=pages['notFound']['seoTitle'],
         description=pages['notFound']['seoDescription'], path='/404.html',
         page_kind='doc', body=notfound_body(pages))

    # ---- prune pages for products that no longer exist -------------------
    # The build only ever writes. Without this, hiding or deleting a product
    # leaves its old directory in the checkout and GitHub Pages keeps serving
    # the page — the one thing hiding is supposed to prevent. Only directories
    # holding nothing but a generated index.html are removed.
    live_slugs = set(by_slug)
    pdir = os.path.join(ROOT, 'proizvod')
    pruned = 0
    if os.path.isdir(pdir):
        for name in sorted(os.listdir(pdir)):
            if name in live_slugs:
                continue
            d = os.path.join(pdir, name)
            if not os.path.isdir(d):
                continue
            if os.listdir(d) != ['index.html']:
                print(f'  ostavljen (nije samo index.html): proizvod/{name}')
                continue
            os.remove(os.path.join(d, 'index.html'))
            os.rmdir(d)
            pruned += 1

    # ---- sitemap + robots ------------------------------------------------
    urls = ['/', '/proizvodi/', '/rasprodaja/', '/kontakt/', '/politika-privatnosti/',
            '/korpa/', '/checkout/'] + [c['href'] for c in categories]
    urls += [f'/proizvod/{p["slug"]}/' for p in by_slug.values()]
    sm = ['<?xml version="1.0" encoding="UTF-8"?>',
          '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for u in urls:
        sm.append(f'  <url><loc>{SITE_URL}{u}</loc></url>')
    sm.append('</urlset>')
    write('sitemap.xml', '\n'.join(sm) + '\n')
    # /admin is the CMS, not content. Keep it out of the index — everything
    # behind it needs a login anyway, so a crawler has nothing to find.
    write('robots.txt',
          f'User-agent: *\nAllow: /\nDisallow: /admin/\n'
          f'Sitemap: {SITE_URL}/sitemap.xml\n')
    # GitHub Pages would otherwise run the output through Jekyll
    write('.nojekyll', '')

    # Every generated file is written with LF. Without this, Git on Windows
    # (core.autocrlf=true) rewrites them to CRLF on checkout and warns on every
    # file, and the whole site looks changed on each build.
    write('.gitattributes', GITATTRIBUTES)

    admin_ver, admin_n = stamp_admin()

    # ---- report ----------------------------------------------------------
    print(f'pages written        : {len(written)}')
    print(f'products             : {len(by_slug)}')
    for c in categories:
        print(f'  {c["label"]:<10}: {counts.get(c["slug"], 0)}')
    print(f'  na stanju  : {sum(1 for p in products if p["available"])}')
    print(f'  rasprodato : {sum(1 for p in products if not p["available"])}')
    print(f'  na sniženju: {len(on_sale)}')
    if hidden:
        print(f'hidden (not built)   : {len(hidden)}')
    if pruned:
        print(f'pages removed        : {pruned}')
    print(f'images present       : {len(have)} (placeholders for the rest)')
    print(f'index.json rows      : {len(rows)}')
    print(f'asset version        : {asset_fingerprint()}')
    if admin_ver:
        print(f'admin version        : {admin_ver} ({admin_n} fajlova)')
    print('links                : ' + ('absolute under ' + base if base else 'relative (portable)'))
    print('header logo          : ' + (logo or 'typographic fallback')
          + (' [' + logo_note + ']' if logo_note else ''))
    print('record label logo    : ' + (label_logo or 'typographic fallback')
          + (' [' + label_note + ']' if label_note else ''))
    print('hero wordmark        : ' + (wordmark or 'typographic fallback')
          + (' [' + wordmark_note + ']' if wordmark_note else ''))


if __name__ == '__main__':
    main()
